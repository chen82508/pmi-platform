"""Race calendar: which (state, office) combinations have elections in a given cycle year.

Loaded from pmi_core/config/race_calendar.yaml, which is auto-generated by
scripts/update_race_calendar.py (Wikipedia-sourced, re-run after special elections).

House elections always cover all 435 districts — not tracked here, just pass-through.
Senate and governor filter based on the calendar.
"""

from __future__ import annotations

from pathlib import Path

try:
    import yaml as _yaml_mod
    _YAML_OK = True
except ImportError:
    _YAML_OK = False

_CALENDAR_PATH = Path(__file__).parent.parent / "config" / "race_calendar.yaml"
_cache: dict | None = None


def _load() -> dict:
    global _cache
    if _cache is not None:
        return _cache
    if not _CALENDAR_PATH.exists():
        raise FileNotFoundError(
            f"race_calendar.yaml not found at {_CALENDAR_PATH}. "
            "Run: python scripts/update_race_calendar.py"
        )
    if not _YAML_OK:
        raise ImportError("PyYAML required: pip install pyyaml")
    with open(_CALENDAR_PATH) as f:
        _cache = _yaml_mod.safe_load(f)
    return _cache


def senate_states_for_cycle(cycle_year: int) -> frozenset[str]:
    """State codes with at least one senate seat on the ballot in cycle_year."""
    data = _load()
    return frozenset(
        code
        for code, years in data.get("senate", {}).items()
        if cycle_year in years
    )


def governor_states_for_cycle(cycle_year: int) -> frozenset[str]:
    """State codes with a governor election in cycle_year."""
    data = _load()
    states: set[str] = set()
    for code, info in data.get("governor", {}).items():
        next_yr: int = info["next"]
        period: int = info["period"]
        # Walk forward from next_yr in period steps until we reach or pass cycle_year.
        yr = next_yr
        while yr <= cycle_year + period:
            if yr == cycle_year:
                states.add(code)
                break
            yr += period
    return frozenset(states)


def has_race(state_code: str, office: str, cycle_year: int) -> bool:
    """True if (state_code, office) has an election in cycle_year."""
    if office == "house":
        return True  # all 435 districts every even year
    if office == "senate":
        return state_code in senate_states_for_cycle(cycle_year)
    if office == "governor":
        return state_code in governor_states_for_cycle(cycle_year)
    return False
